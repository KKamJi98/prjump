#!/usr/bin/env bash
# Render the Homebrew formula for prj from the release archives' checksums.
#
# usage: render-formula.sh <version> <dist-dir>
#   <dist-dir> holds prj-<version>-<target>.tar.gz.sha256 for the four
#   macOS/Linux targets. The formula is written to stdout.
set -euo pipefail

if [[ $# -ne 2 ]]; then
  echo "usage: $0 <version> <dist-dir>" >&2
  exit 2
fi

version="$1"
dist="$2"

if [[ ! "${version}" =~ ^[0-9]+\.[0-9]+\.[0-9]+$ ]]; then
  echo "version must look like 1.2.3, got '${version}'" >&2
  exit 2
fi

base="https://github.com/KKamJi98/prjump/releases/download/v${version}"

sha() {
  local file="${dist}/prj-${version}-$1.tar.gz.sha256"
  local sum
  sum="$(cut -d ' ' -f 1 "${file}")"
  if [[ ! "${sum}" =~ ^[0-9a-f]{64}$ ]]; then
    echo "bad checksum in ${file}" >&2
    exit 1
  fi
  printf '%s' "${sum}"
}

cat <<EOF
# Generated by KKamJi98/prjump .github/workflows/release.yml. Do not edit here.
class Prj < Formula
  desc "Open GitHub/Bitbucket Cloud pull request pages from the CLI"
  homepage "https://github.com/KKamJi98/prjump"
  version "${version}"
  license "MIT"

  on_macos do
    on_arm do
      url "${base}/prj-${version}-aarch64-apple-darwin.tar.gz"
      sha256 "$(sha aarch64-apple-darwin)"
    end
    on_intel do
      url "${base}/prj-${version}-x86_64-apple-darwin.tar.gz"
      sha256 "$(sha x86_64-apple-darwin)"
    end
  end

  on_linux do
    on_arm do
      url "${base}/prj-${version}-aarch64-unknown-linux-musl.tar.gz"
      sha256 "$(sha aarch64-unknown-linux-musl)"
    end
    on_intel do
      url "${base}/prj-${version}-x86_64-unknown-linux-musl.tar.gz"
      sha256 "$(sha x86_64-unknown-linux-musl)"
    end
  end

  def install
    bin.install "prj"
  end

  test do
    assert_match "prj #{version}", shell_output("#{bin}/prj --version")
  end
end
EOF
